// The attribute editor's model: which template, its attributes' text, the NameID and custom
// attributes. Building it gives the identity to sign in (or mint a Response) as.

import { load, save } from "@/lib/storage"
import { createStore } from "@/lib/store"
import type {
  AttributeField,
  Attributes,
  EditorData,
  Entry,
  Identity,
  Preset,
} from "@/lib/types"

export const NAME_ID = {
  EMAIL: "urn:oasis:names:tc:SAML:1.1:nameid-format:emailAddress",
  PERSISTENT: "urn:oasis:names:tc:SAML:2.0:nameid-format:persistent",
  TRANSIENT: "urn:oasis:names:tc:SAML:2.0:nameid-format:transient",
  UNSPECIFIED: "urn:oasis:names:tc:SAML:1.1:nameid-format:unspecified",
}

/** The last part of a URN or URL: `urn:…:emailAddress` is `emailAddress`. */
export const short = (uri: string | null | undefined) =>
  (uri ?? "").split(/[:/#]/).filter(Boolean).pop() ?? ""

export type EditorState = {
  preset: string
  /** Each attribute's text (a list's values one per line), by name. */
  values: Record<string, string>
  /** Custom attributes, as JSON text. */
  custom: string
  nameId: string
  nameIdFormat: string
  /** The NameID follows the template (an attribute, or generated by the server). */
  nameIdAuto: boolean
  step: number
  showAll: boolean
}

export const presetOf = (presets: Preset[], id: string) =>
  presets.find((p) => p.id === id) ?? presets[0]

function fieldText(a: AttributeField, v: unknown): string {
  if (v == null) return ""
  const text = (x: unknown) => (typeof x === "string" ? x : JSON.stringify(x))
  const list = Array.isArray(v) ? v.map(text) : [text(v)]
  return a.kind === "list" ? list.join("\n") : list.join(", ")
}

const first = (v: string | string[] | undefined) =>
  (Array.isArray(v) ? v[0] : v) ?? ""

/** The attribute values the editor describes, and what's wrong with them. */
export function attributesOf(presets: Preset[], state: EditorState) {
  const p = presetOf(presets, state.preset)
  const out: Attributes = {}
  const errors: string[] = []
  for (const a of p.attributes) {
    const v = state.values[a.name] ?? ""
    if (a.kind === "list") {
      const items = v
        .split("\n")
        .map((s) => s.trim())
        .filter(Boolean)
      if (items.length) out[a.name] = items
    } else if (v !== "") out[a.name] = v
  }
  if (state.custom.trim()) {
    try {
      const o: unknown = JSON.parse(state.custom)
      if (!o || typeof o !== "object" || Array.isArray(o)) {
        errors.push("Custom attributes: must be a JSON object")
      } else {
        for (const [k, v] of Object.entries(o)) {
          if (v === null) delete out[k]
          else if (
            typeof v === "string" ||
            (Array.isArray(v) && v.every((x) => typeof x === "string"))
          ) {
            out[k] = v as string | string[]
          } else {
            errors.push(
              `Custom attributes: "${k}" must be a string, a list of strings, or null`
            )
          }
        }
      }
    } catch (e) {
      errors.push(
        `Custom attributes: ${e instanceof Error ? e.message : String(e)}`
      )
    }
  }
  return { attributes: out, errors }
}

/**
 * The attribute the NameID follows: the template's own source in its own format (Entra ID's
 * UPN), else the email attribute for an emailAddress NameID; none means the template's example.
 */
export function nameIdSource(presets: Preset[], state: EditorState) {
  const p = presetOf(presets, state.preset)
  if (p.name_id_from && state.nameIdFormat === p.name_id_format) {
    return p.name_id_from
  }
  if (state.nameIdFormat === NAME_ID.EMAIL) {
    return p.email_attribute ?? p.name_id_from
  }
  return p.name_id_from
}

/** The NameID the template implies for the attributes ("" means generated by the server). */
export function derivedNameId(presets: Preset[], state: EditorState) {
  const p = presetOf(presets, state.preset)
  if (
    state.nameIdFormat === NAME_ID.PERSISTENT ||
    state.nameIdFormat === NAME_ID.TRANSIENT
  ) {
    return ""
  }
  const source = nameIdSource(presets, state)
  const attrs = attributesOf(presets, state).attributes
  return (
    (source ? first(attrs[source]) : "") || (source ? "" : p.name_id_example)
  )
}

/** The identity the editor describes, and what's wrong with it. */
export function build(presets: Preset[], state: EditorState) {
  const { attributes, errors } = attributesOf(presets, state)
  const identity: Identity = {
    name_id: state.nameIdAuto ? derivedNameId(presets, state) : state.nameId,
    name_id_format: state.nameIdFormat,
    attributes,
  }
  return { identity, errors }
}

/**
 * The editor showing an identity: its template's attributes filled in and the others as custom
 * ones. Without one, it's the template's defaults (custom attributes are kept).
 */
export function loadIdentity(
  state: EditorState,
  data: EditorData,
  presetId: string,
  identity: Identity | null
): EditorState {
  const p =
    data.presets.find((x) => x.id === presetId) ??
    presetOf(data.presets, data.defaultPreset)
  const attrs = identity?.attributes ?? null
  const values: EditorState["values"] = {}
  for (const a of p.attributes) {
    values[a.name] = fieldText(a, attrs ? attrs[a.name] : a.default)
  }
  if (!identity) {
    return {
      ...state,
      preset: p.id,
      values,
      nameIdFormat: data.requestedNameIdFormat ?? p.name_id_format,
      nameIdAuto: true,
      nameId: "",
    }
  }
  const names = new Set(p.attributes.map((a) => a.name))
  const custom = Object.fromEntries(
    Object.entries(identity.attributes ?? {}).filter(([k]) => !names.has(k))
  )
  const next: EditorState = {
    ...state,
    preset: p.id,
    values,
    custom: Object.keys(custom).length ? JSON.stringify(custom, null, 2) : "",
  }
  // A NameID format the service provider asked for wins over the stored identity's.
  const requested = data.requestedNameIdFormat
  if (requested && requested !== identity.name_id_format) {
    return { ...next, nameIdFormat: requested, nameId: "", nameIdAuto: true }
  }
  const withFormat = {
    ...next,
    nameIdFormat: identity.name_id_format || p.name_id_format,
    nameId: identity.name_id || "",
  }
  return {
    ...withFormat,
    nameIdAuto:
      !withFormat.nameId ||
      withFormat.nameId === derivedNameId(data.presets, withFormat),
  }
}

/** The editor as a page first shows it. */
export function initialEditor(data: EditorData): EditorState {
  const blank: EditorState = {
    preset: data.defaultPreset,
    values: {},
    custom: "",
    nameId: "",
    nameIdFormat: "",
    nameIdAuto: true,
    step: data.tenantPreset ? 1 : 0,
    showAll: false,
  }
  const prev = data.previous
  let state =
    prev &&
    data.mode !== "dev" &&
    data.presets.some((p) => p.id === prev.preset)
      ? loadIdentity(blank, data, prev.preset, prev)
      : loadIdentity(blank, data, data.defaultPreset, null)
  const hint = data.loginHint
  if (hint) {
    const p = presetOf(data.presets, state.preset)
    if (hint.includes("@") && p.email_attribute) {
      const values = { ...state.values, [p.email_attribute]: hint }
      if (
        p.name_id_from &&
        p.name_id_from !== p.email_attribute &&
        (state.values[p.name_id_from] ?? "").includes("@")
      ) {
        values[p.name_id_from] = hint
      }
      state = { ...state, values }
    } else {
      state = { ...state, nameId: hint, nameIdAuto: false }
    }
  }
  // An AuthnRequest that names a Subject only succeeds if you sign in as it (Profiles 4.1.4.1).
  if (data.subject) {
    state = { ...state, nameId: data.subject.nameId, nameIdAuto: false }
    if (data.subject.format && data.subject.format !== NAME_ID.UNSPECIFIED) {
      state = { ...state, nameIdFormat: data.subject.format }
    }
  }
  return state
}

/** A short name for an identity: its email, else its NameID. */
export function describe(presets: Preset[], entry: Entry) {
  const attrs = entry.identity.attributes ?? {}
  const p = presets.find((x) => x.id === entry.preset)
  const email = p?.email_attribute
    ? first(attrs[p.email_attribute])
    : Object.values(attrs)
        .map(first)
        .find((v) => v.includes("@"))
  return email || entry.identity.name_id || "identity"
}

/** The Subject and AttributeStatement as this template would write them. */
export function previewXml(
  presets: Preset[],
  state: EditorState,
  identity: Identity
) {
  const p = presetOf(presets, state.preset)
  const s = p.style
  const q = (local: string) =>
    s.assertion_prefix ? `${s.assertion_prefix}:${local}` : local
  const esc = (v: string) =>
    v.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;")
  const lines = [
    `<${q("Subject")}>`,
    `  <${q("NameID")} Format="${esc(identity.name_id_format)}">${esc(identity.name_id || "(generated)")}</${q("NameID")}>`,
    `</${q("Subject")}>`,
  ]
  const entries = Object.entries(identity.attributes)
  // Templates that send every attribute (OneLogin) send the missing ones empty.
  if (p.send_empty_attributes) {
    for (const a of p.attributes) {
      if (!(a.name in identity.attributes)) entries.push([a.name, ""])
    }
  }
  if (entries.length) {
    lines.push(`<${q("AttributeStatement")}>`)
    for (const [name, value] of entries) {
      const a = p.attributes.find((x) => x.name === name)
      const format = a?.name_format ?? s.name_format
      let open = `  <${q("Attribute")} Name="${esc(name)}"`
      if (format) open += ` NameFormat="${esc(format)}"`
      if (a?.friendly_name) open += ` FriendlyName="${esc(a.friendly_name)}"`
      lines.push(`${open}>`)
      for (const v of Array.isArray(value) ? value : [value]) {
        const type = s.xsi_type ? ` xsi:type="${s.xsi_type}"` : ""
        lines.push(
          `    <${q("AttributeValue")}${type}>${esc(v)}</${q("AttributeValue")}>`
        )
      }
      lines.push(`  </${q("Attribute")}>`)
    }
    lines.push(`</${q("AttributeStatement")}>`)
  }
  return lines.join("\n")
}

// Saved identities and the last one used live in this browser, under the previous UI's keys.

export type SavedEntry = Entry & { name: string }

/** The saved identities, newest first. */
export const savedIdentities = createStore<SavedEntry[]>(
  load<SavedEntry[]>("identities", []).filter((s) => s?.identity)
)
savedIdentities.subscribe(() => save("identities", savedIdentities.get()))

/** Saves an identity under a name, replacing one with the same name. */
export function saveIdentity(entry: SavedEntry) {
  savedIdentities.set((list) => [
    entry,
    ...list.filter((s) => s.name !== entry.name),
  ])
}

export const lastIdentity = () => load<Entry | null>("last", null)
export const rememberLast = (entry: Entry) => save("last", entry)

/** What's kept of an editor's identity: a NameID that follows the template isn't. */
export const storedEntry = (state: EditorState, identity: Identity): Entry => ({
  preset: state.preset,
  identity: { ...identity, name_id: state.nameIdAuto ? "" : identity.name_id },
})

/** JSON with sorted keys, to compare identities whatever their key order. */
function stable(v: unknown): string {
  if (Array.isArray(v)) return `[${v.map(stable).join(",")}]`
  if (v && typeof v === "object") {
    return `{${Object.keys(v)
      .sort()
      .map(
        (k) =>
          `${JSON.stringify(k)}:${stable((v as Record<string, unknown>)[k])}`
      )
      .join(",")}}`
  }
  return JSON.stringify(v)
}

export const entryKey = (e: Entry) => stable([e.preset, e.identity?.attributes])
