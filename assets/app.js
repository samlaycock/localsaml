// localsaml page script: XML highlighting and copy buttons everywhere, the identity wizard shared
// by the login and assertion generator pages, the generator's tools, and the request inspector.
'use strict';

const h = (tag, attrs = {}, ...children) => {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (v == null || v === false) continue;
    if (k.startsWith('on')) el.addEventListener(k.slice(2), v);
    else if (k === 'class') el.className = v;
    else if (k === 'style') el.setAttribute('style', v);
    else if (k === 'value') el.value = v;
    else if (k in el && typeof v !== 'string') el[k] = v;
    else el.setAttribute(k, v === true ? '' : v);
  }
  for (const c of children.flat()) if (c != null) el.append(c.nodeType ? c : document.createTextNode(c));
  return el;
};

// ------------------------------------------------------------------ XML and copy buttons
const escapeHtml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Highlight indented XML (tags, attributes, values, text and comments). */
function highlightXml(xml) {
  return xml.replace(/<!--[\s\S]*?-->|<[^>]+>|[^<]+/g, (tok) => {
    if (tok.startsWith('<!--')) return `<span class="x-com">${escapeHtml(tok)}</span>`;
    if (tok.startsWith('<')) {
      // Attributes first: the tag-name replacement adds markup the attribute pattern would match.
      return escapeHtml(tok)
        .replace(/([\w:.-]+)=("[^"]*")/g, '<span class="x-attr">$1</span>=<span class="x-val">$2</span>')
        .replace(/^(&lt;\/?)([\w:.-]+)/, '$1<span class="x-tag">$2</span>');
    }
    return tok.trim() ? `<span class="x-text">${escapeHtml(tok)}</span>` : escapeHtml(tok);
  });
}

function xmlPre(xml) {
  const pre = h('pre', { class: 'code xml' });
  pre.innerHTML = highlightXml(xml);
  return pre;
}

function copyBtn(getText, label = 'Copy') {
  return h('button', { type: 'button', class: 'btn small', onclick: async (e) => {
    await navigator.clipboard.writeText(typeof getText === 'function' ? getText() : getText);
    const b = e.target; const old = b.textContent; b.textContent = 'Copied'; setTimeout(() => (b.textContent = old), 1200);
  } }, label);
}

document.querySelectorAll('pre.code.xml').forEach((pre) => { pre.innerHTML = highlightXml(pre.textContent); });
document.addEventListener('click', async (e) => {
  const btn = e.target.closest('[data-copy-next]');
  if (!btn) return;
  const target = btn.closest('.snippet')?.querySelector('pre') || btn.nextElementSibling;
  if (!target) return;
  await navigator.clipboard.writeText(target.textContent);
  const old = btn.textContent; btn.textContent = 'Copied'; setTimeout(() => (btn.textContent = old), 1200);
});

// ------------------------------------------------------------------ identity wizard
// Saved identities sit at the top for one-click reuse; below them a short wizard
// (template -> attributes -> subject and custom attributes [-> response options]) builds a new one.
// The page's own submit buttons stay server-rendered so it works without JS too.
(function () {
  const dataEl = document.getElementById('lo-data');
  if (!dataEl) return;
  const data = JSON.parse(dataEl.textContent);
  const presets = data.presets;
  const byId = Object.fromEntries(presets.map((p) => [p.id, p]));
  const LS_SAVED = 'localsaml.identities';
  const LS_LAST = 'localsaml.last';
  const LS_REVIEW = 'localsaml.review';
  const root = document.getElementById('lo-editor');
  const form = document.getElementById('lo-form');
  const isDev = data.mode === 'dev';
  const $ = (id) => document.getElementById(id);
  const NS = {
    EMAIL: 'urn:oasis:names:tc:SAML:1.1:nameid-format:emailAddress',
    PERSISTENT: 'urn:oasis:names:tc:SAML:2.0:nameid-format:persistent',
    TRANSIENT: 'urn:oasis:names:tc:SAML:2.0:nameid-format:transient',
    UNSPECIFIED: 'urn:oasis:names:tc:SAML:1.1:nameid-format:unspecified',
  };
  const short = (uri) => (uri || '').split(':').pop();

  // ---------------------------------------------------------------- identity state
  // `nameIdAuto`: the NameID follows the template (an attribute, or generated by the server).
  const state = { preset: null, values: {}, custom: '', nameId: '', nameIdFormat: '', nameIdAuto: true, step: 0, showAll: false };

  const fieldText = (a, v) => {
    if (v == null) return '';
    if (a.kind === 'list') return (Array.isArray(v) ? v : [v]).join('\n');
    return Array.isArray(v) ? v.join(', ') : String(v);
  };

  /** Load an identity into the editor; with none, switch template and keep custom attributes. */
  function load(presetId, identity) {
    const p = byId[presetId] || byId[data.defaultPreset] || presets[0];
    state.preset = p.id;
    state.values = {};
    const attrs = identity ? identity.attributes || {} : null;
    for (const a of p.attributes) state.values[a.name] = fieldText(a, attrs ? attrs[a.name] : a.default);
    if (!identity) {
      state.nameIdFormat = data.requestedNameIdFormat || p.name_id_format;
      state.nameIdAuto = true;
      state.nameId = '';
      return;
    }
    const names = new Set(p.attributes.map((a) => a.name));
    const custom = Object.fromEntries(Object.entries(attrs).filter(([k]) => !names.has(k)));
    state.custom = Object.keys(custom).length ? JSON.stringify(custom, null, 2) : '';
    // A NameID format the service provider asked for wins over the stored identity's.
    const requested = data.requestedNameIdFormat;
    if (requested && requested !== identity.name_id_format) {
      state.nameIdFormat = requested;
      state.nameId = '';
      state.nameIdAuto = true;
      return;
    }
    state.nameIdFormat = identity.name_id_format || p.name_id_format;
    state.nameId = identity.name_id || '';
    state.nameIdAuto = !state.nameId || state.nameId === derivedNameId();
  }

  /** Attribute values from the editor: {attributes, errors}. */
  function attributes() {
    const p = byId[state.preset];
    const out = {};
    const errors = [];
    for (const a of p.attributes) {
      const v = state.values[a.name] ?? '';
      if (a.kind === 'list') {
        const items = String(v).split('\n').map((s) => s.trim()).filter(Boolean);
        if (items.length) out[a.name] = items;
      } else if (String(v) !== '') out[a.name] = String(v);
    }
    if (state.custom && state.custom.trim()) {
      try {
        const o = JSON.parse(state.custom);
        if (!o || typeof o !== 'object' || Array.isArray(o)) errors.push('Custom attributes: must be a JSON object');
        else for (const [k, v] of Object.entries(o)) {
          if (v === null) delete out[k];
          else if (typeof v === 'string' || (Array.isArray(v) && v.every((x) => typeof x === 'string'))) out[k] = v;
          else errors.push(`Custom attributes: "${k}" must be a string, a list of strings, or null`);
        }
      } catch (e) { errors.push(`Custom attributes: ${e.message}`); }
    }
    return { attributes: out, errors };
  }

  const first = (v) => (Array.isArray(v) ? v[0] : v) || '';

  /** The NameID the template implies for the current attributes ('' = generated by the server). */
  function derivedNameId() {
    const p = byId[state.preset];
    const attrs = attributes().attributes;
    if (state.nameIdFormat === NS.PERSISTENT || state.nameIdFormat === NS.TRANSIENT) return '';
    return first(attrs[nameIdSource()]) || (nameIdSource() ? '' : p.name_id_example);
  }

  /** The attribute the NameID follows: the template's own source in its own format (Entra ID's
   *  UPN), else the email attribute for an emailAddress NameID; none means the template example. */
  function nameIdSource() {
    const p = byId[state.preset];
    if (p.name_id_from && state.nameIdFormat === p.name_id_format) return p.name_id_from;
    if (state.nameIdFormat === NS.EMAIL) return p.email_attribute || p.name_id_from;
    return p.name_id_from;
  }

  /** Build {identity, errors} from the editor state. */
  function build() {
    const { attributes: attrs, errors } = attributes();
    const nameId = state.nameIdAuto ? derivedNameId() : state.nameId;
    return { identity: { name_id: nameId, name_id_format: state.nameIdFormat, attributes: attrs }, errors };
  }

  function applyLoginHint(hint) {
    if (!hint) return;
    const p = byId[state.preset];
    if (hint.includes('@') && p.email_attribute) {
      state.values[p.email_attribute] = hint;
      if (p.name_id_from && p.name_id_from !== p.email_attribute && String(state.values[p.name_id_from] || '').includes('@')) {
        state.values[p.name_id_from] = hint;
      }
    } else {
      state.nameId = hint;
      state.nameIdAuto = false;
    }
  }

  const describe = (identity) => {
    const attrs = identity.attributes || {};
    const p = byId[identity.preset];
    const email = p && p.email_attribute ? first(attrs[p.email_attribute]) : Object.values(attrs).map(first).find((v) => String(v).includes('@'));
    return email || identity.name_id || 'identity';
  };

  // ---------------------------------------------------------------- saved identities
  // Saved shape: {name, preset, identity: {name_id, name_id_format, attributes}}.
  const readJson = (key, fallback) => { try { return JSON.parse(localStorage.getItem(key)) ?? fallback; } catch { return fallback; } };
  const saved = () => readJson(LS_SAVED, []);
  const storeSaved = (list) => localStorage.setItem(LS_SAVED, JSON.stringify(list));
  const rememberLast = (entry) => localStorage.setItem(LS_LAST, JSON.stringify(entry));

  function saveCurrent(name) {
    const { identity, errors } = build();
    if (errors.length) { refresh(); return false; }
    const next = saved().filter((s) => s.name !== name);
    next.unshift({ name, preset: state.preset, identity: { ...identity, name_id: state.nameIdAuto ? '' : identity.name_id } });
    storeSaved(next);
    return true;
  }

  // ---------------------------------------------------------------- actions
  function go() {
    if (isDev) { $('dev-generate').click(); return; }
    form.requestSubmit(form.querySelector('button[value=approve]'));
  }

  function useIdentity(entry) {
    load(entry.preset, entry.identity);
    render();
    go();
  }

  function editIdentity(entry) {
    load(entry.preset, entry.identity);
    state.step = 1;
    render();
  }

  // ---------------------------------------------------------------- rendering
  const STEPS = [
    { id: 'template', label: 'Template' },
    { id: 'attributes', label: 'Attributes' },
    { id: 'subject', label: 'Subject & custom' },
    ...(isDev ? [{ id: 'options', label: 'Response options' }] : []),
  ];
  let previewEl, errorEl, nameIdInput, nameIdTag;

  function refresh() {
    const { identity, errors } = build();
    if (previewEl) previewEl.innerHTML = highlightXml(previewXml(identity));
    if (errorEl) {
      errorEl.textContent = errors.join(' · ');
      errorEl.hidden = !errors.length;
    }
    if (nameIdInput && state.nameIdAuto) {
      nameIdInput.value = identity.name_id;
      nameIdInput.placeholder = state.nameIdFormat === NS.TRANSIENT ? 'generated: new each session' : state.nameIdFormat === NS.PERSISTENT ? 'generated: stable per service provider' : '';
    }
    if (nameIdTag) {
      const p = byId[state.preset];
      nameIdTag.replaceChildren(state.nameIdAuto
        ? (identity.name_id
          ? (nameIdSource() ? `follows ${(p.attributes.find((a) => a.name === nameIdSource()) || {}).label || shortName(nameIdSource())}` : 'template default')
          : 'generated by localsaml')
        : h('a', { href: '#', onclick: (e) => { e.preventDefault(); state.nameIdAuto = true; refresh(); } }, '↺ follow the template'));
    }
    const nameInput = $('lo-save-name');
    if (nameInput && !nameInput.dataset.touched) nameInput.value = describe({ preset: state.preset, ...identity });
  }

  const shortName = (name) => name.split(/[/:#]/).filter(Boolean).pop() || name;

  /** The Subject and AttributeStatement as this template would write them. */
  function previewXml(identity) {
    const p = byId[state.preset];
    const s = p.style;
    const q = (local) => (s.assertion_prefix ? `${s.assertion_prefix}:${local}` : local);
    const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
    const lines = [
      `<${q('Subject')}>`,
      `  <${q('NameID')} Format="${esc(identity.name_id_format)}">${esc(identity.name_id || '(generated)')}</${q('NameID')}>`,
      `</${q('Subject')}>`,
    ];
    const entries = Object.entries(identity.attributes);
    // Templates that send every parameter (OneLogin) send the missing ones empty.
    if (p.send_empty_attributes) {
      for (const a of p.attributes) if (!(a.name in identity.attributes)) entries.push([a.name, '']);
    }
    if (entries.length) {
      lines.push(`<${q('AttributeStatement')}>`);
      for (const [name, value] of entries) {
        const a = p.attributes.find((x) => x.name === name);
        const format = (a && a.name_format) || s.name_format;
        let open = `  <${q('Attribute')} Name="${esc(name)}"`;
        if (format) open += ` NameFormat="${esc(format)}"`;
        if (a && a.friendly_name) open += ` FriendlyName="${esc(a.friendly_name)}"`;
        lines.push(`${open}>`);
        for (const v of Array.isArray(value) ? value : [value]) {
          const type = s.xsi_type ? ` xsi:type="${s.xsi_type}"` : '';
          lines.push(`    <${q('AttributeValue')}${type}>${esc(v)}</${q('AttributeValue')}>`);
        }
        lines.push(`  </${q('Attribute')}>`);
      }
      lines.push(`</${q('AttributeStatement')}>`);
    }
    return lines.join('\n');
  }

  function quickSection() {
    const items = [];
    if (data.previous && !isDev) items.push({ kind: 'session', label: 'Active session', entry: { preset: data.previous.preset, identity: data.previous } });
    // Users declared in localsaml.toml, shared by everyone using this server.
    (data.users || []).forEach((u) => items.push({ kind: 'user', label: u.label || u.id, entry: { preset: u.preset, identity: u.identity } }));
    // "Last used" only when it isn't already offered as the session, a user or a saved identity.
    const stable = (v) => Array.isArray(v) ? `[${v.map(stable).join(',')}]`
      : v && typeof v === 'object' ? `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${stable(v[k])}`).join(',')}}`
      : JSON.stringify(v);
    const key = (e) => stable([e.preset, e.identity && e.identity.attributes]);
    const last = readJson(LS_LAST, null);
    const offered = new Set([...items.map((i) => key(i.entry)), ...saved().map(key)]);
    if (last && last.identity && !offered.has(key(last))) items.push({ kind: 'last', label: 'Last used', entry: last });
    saved().forEach((s, i) => s.identity && items.push({ kind: 'saved', label: s.name, entry: s, index: i }));

    // An AuthnRequest naming a Subject only gets an assertion about that subject (Profiles 4.1.4.1).
    const subject = data.subject && data.subject.nameId;
    const mismatch = (identity) => subject && identity && identity.name_id && identity.name_id !== subject;
    const cards = items.map((item) => {
      const p = byId[item.entry.preset] || presets[0];
      const who = describe({ preset: p.id, ...item.entry.identity });
      const named = item.kind === 'saved' || item.kind === 'user';
      return h('div', { class: `quick-card is-${item.kind}`, style: `--c:${p.color}` },
        h('div', { class: 'quick-meta' },
          h('span', { class: 'quick-label' }, named ? item.label : h('span', {}, h('em', {}, item.label), ` · ${who}`)),
          h('span', { class: 'quick-provider' }, h('span', { class: 'dot' }), p.name, named && item.label !== who ? ` · ${who}` : null,
            item.kind === 'user' ? h('span', { class: 'quick-tag', title: 'Declared in localsaml.toml' }, 'config') : null,
            mismatch(item.entry.identity)
              ? h('span', { class: 'quick-tag warn', title: `Its NameID is ${item.entry.identity.name_id}` }, 'not the requested subject')
              : null)),
        h('div', { class: 'quick-actions' },
          h('button', { type: 'button', class: 'btn small primary', onclick: () => useIdentity(item.entry) }, isDev ? 'Generate' : 'Sign in'),
          h('button', { type: 'button', class: 'btn small ghost', onclick: () => editIdentity(item.entry) }, 'Edit'),
          item.kind === 'saved'
            ? h('button', { type: 'button', class: 'btn small ghost icon', title: 'Delete', onclick: () => {
                const list = saved(); list.splice(item.index, 1); storeSaved(list); render();
              } }, '×')
            : null));
    });

    return h('section', { class: 'quick' },
      h('div', { class: 'section-title' }, isDev ? 'Saved identities' : 'Quick sign in'),
      subject && !isDev
        ? h('p', { class: 'notice warn small' }, 'This request is for the subject ', h('code', {}, subject),
            '. Only signing in with that NameID (pre-filled below) gets an assertion; any other identity gets an UnknownPrincipal error.')
        : null,
      cards.length
        ? h('div', { class: 'quick-list' }, cards)
        : h('p', { class: 'muted small' }, 'Identities you save (bottom of the page) show up here for one-click reuse.'));
  }

  function stepNav() {
    return h('nav', { class: 'steps' }, STEPS.map((s, i) =>
      h('button', {
        type: 'button',
        class: `step ${i === state.step ? 'current' : ''} ${i < state.step ? 'done' : ''}`,
        onclick: () => { state.step = i; render(); },
      }, h('span', { class: 'step-num' }, String(i + 1)), s.label)));
  }

  function fieldInput(a) {
    const v = state.values[a.name] ?? '';
    const id = `f-${a.name.replace(/[^a-z0-9]/gi, '_')}`;
    const set = (val) => { state.values[a.name] = val; refresh(); };
    let input;
    if (a.kind === 'list') {
      input = h('textarea', { id, rows: Math.max(2, String(v).split('\n').length), spellcheck: false, placeholder: 'one value per line', oninput: (e) => set(e.target.value) });
      input.value = v;
    } else {
      input = h('input', { id, type: 'text', value: v, spellcheck: false, oninput: (e) => set(e.target.value) });
    }
    return h('label', { class: `field ${a.kind === 'list' || a.name.length > 40 ? 'wide' : ''}`, for: id },
      h('span', { class: 'field-label' }, a.label, h('code', { class: 'claim-name', title: a.name }, a.friendly_name || a.name)),
      input,
      a.help ? h('small', { class: 'help' }, a.help) : null);
  }

  function templateStep() {
    const pinned = data.tenantPreset ? byId[data.tenantPreset] : null;
    return [
      h('p', { class: 'muted step-intro' }, 'Which identity provider should this look like? This sets the attribute names, NameID, signing and XML style.',
        pinned ? ` This issuer emulates ${pinned.name}.` : ''),
      h('div', { class: 'provider-grid' }, presets.map((q) =>
        h('button', {
          type: 'button',
          class: `provider-card ${q.id === state.preset ? 'active' : ''}`,
          style: `--c:${q.color}`,
          onclick: () => { if (q.id !== state.preset) load(q.id, null); state.step = 1; render(); },
        },
        h('span', { class: 'provider-name' }, h('span', { class: 'dot' }), q.name),
        h('span', { class: 'provider-desc' }, q.description)))),
    ];
  }

  function attributesStep() {
    const p = byId[state.preset];
    const common = p.attributes.filter((a) => !a.advanced);
    const advanced = p.attributes.filter((a) => a.advanced);
    return [
      h('p', { class: 'muted step-intro' }, `${p.name} attributes. Empty ones are left out of the assertion.`),
      h('div', { class: 'fields' }, common.map(fieldInput)),
      advanced.length
        ? h('button', { type: 'button', class: 'btn small ghost more', onclick: () => { state.showAll = !state.showAll; render(); } },
            state.showAll ? 'Hide extra attributes' : `Show all attributes (${advanced.length} more)`)
        : null,
      state.showAll && advanced.length ? h('div', { class: 'fields' }, advanced.map(fieldInput)) : null,
    ];
  }

  function subjectStep() {
    const formats = [...new Set([state.nameIdFormat, ...(data.nameIdFormats || [])])];
    const select = h('select', { onchange: (e) => { state.nameIdFormat = e.target.value; state.nameIdAuto = true; refresh(); } },
      formats.map((f) => h('option', { value: f, selected: f === state.nameIdFormat }, short(f))));
    nameIdInput = h('input', { type: 'text', spellcheck: false, oninput: (e) => { state.nameId = e.target.value; state.nameIdAuto = false; refresh(); } });
    if (!state.nameIdAuto) nameIdInput.value = state.nameId;
    nameIdTag = h('span', { class: 'auto-tag' });
    const custom = h('textarea', { rows: 6, spellcheck: false, placeholder: '{\n  "department": "Engineering",\n  "memberOf": ["admins", "developers"],\n  "firstName": null\n}', oninput: (e) => { state.custom = e.target.value; refresh(); } });
    custom.value = state.custom;
    previewEl = h('pre', { class: 'code xml preview' });
    const requested = data.requestedNameIdFormat
      ? h('small', { class: 'help' }, `The service provider asked for ${short(data.requestedNameIdFormat)}.`) : null;
    return [
      h('p', { class: 'muted step-intro' }, 'The subject NameID, and any extra attributes. Persistent and transient NameIDs are generated unless you type one.'),
      h('div', { class: 'fields' },
        h('label', { class: 'field' }, h('span', { class: 'field-label' }, 'NameID format'), select, requested),
        h('label', { class: 'field' }, h('span', { class: 'field-label' }, 'NameID'), h('div', { class: 'name-id-row' }, nameIdInput), nameIdTag)),
      h('div', { class: 'customs' },
        h('label', { class: 'field wide' }, h('span', { class: 'field-label' }, 'Custom attributes', h('small', { class: 'muted' }, 'JSON: strings or lists of strings; null removes one')), custom)),
      h('div', { class: 'section-title' }, 'Preview ', h('small', { class: 'muted' }, '(the Issuer, Conditions, AuthnStatement and signatures are added by the server)')),
      previewEl,
    ];
  }

  let devOptions;
  function optionsStep() {
    devOptions.hidden = false;
    return [h('p', { class: 'muted step-intro' }, 'Who the Response is for, how it is signed and encrypted, and any deliberate defects.'), devOptions];
  }

  function render() {
    previewEl = null; nameIdInput = null; nameIdTag = null;
    const step = STEPS[state.step].id;
    const panel = { template: templateStep, attributes: attributesStep, subject: subjectStep, options: optionsStep }[step]();
    const last = state.step === STEPS.length - 1;
    errorEl = h('p', { class: 'notice error', hidden: true });
    root.replaceChildren(
      quickSection(),
      h('section', { class: 'wizard' },
        h('div', { class: 'section-title' }, isDev ? 'New response' : 'New identity'),
        stepNav(),
        h('div', { class: 'step-panel' }, panel),
        h('div', { class: 'step-footer' },
          state.step > 0 ? h('button', { type: 'button', class: 'btn small ghost', onclick: () => { state.step--; render(); } }, '← Back') : h('span'),
          !last ? h('button', { type: 'button', class: 'btn small', onclick: () => { state.step++; render(); } }, `Next: ${STEPS[state.step + 1].label} →`) : null)),
      errorEl);
    refresh();
  }

  /** "Save identity" sits next to the page's Sign in / Generate button, so it's visible at every step. */
  function mountSaveBar() {
    const actions = (form || root.parentElement).querySelector('.actions');
    const name = h('input', { id: 'lo-save-name', class: 'save-name', placeholder: 'Name', oninput: (e) => (e.target.dataset.touched = '1') });
    const btn = h('button', { type: 'button', class: 'btn ghost', onclick: () => {
      const label = name.value.trim() || describe({ preset: state.preset, ...build().identity });
      if (saveCurrent(label)) { btn.textContent = 'Saved ✓'; setTimeout(() => (btn.textContent = 'Save identity'), 1400); render(); }
    } }, 'Save identity');
    actions.classList.add('action-bar');
    actions.append(h('div', { class: 'save-bar' }, name, btn));
  }

  function syncHidden() {
    const { identity, errors } = build();
    if (!errors.length) rememberLast({ preset: state.preset, identity: { ...identity, name_id: state.nameIdAuto ? '' : identity.name_id } });
    if (!form) return errors;
    form.elements.preset.value = state.preset;
    form.elements.identity.value = JSON.stringify(identity);
    return errors;
  }

  // ---------------------------------------------------------------- init
  if (isDev) {
    devOptions = $('dev-options');
    devOptions.remove();
  }
  const prev = data.previous;
  if (prev && byId[prev.preset] && !isDev) load(prev.preset, prev);
  else load(data.defaultPreset, null);
  applyLoginHint(data.loginHint);
  // An AuthnRequest that names a Subject only succeeds if you sign in as it (Profiles 4.1.4.1).
  if (data.subject) {
    state.nameId = data.subject.nameId;
    state.nameIdAuto = false;
    if (data.subject.format && data.subject.format !== NS.UNSPECIFIED) state.nameIdFormat = data.subject.format;
  }
  if (data.tenantPreset) state.step = 1;
  render();
  mountSaveBar();
  refresh(); // fills in the save bar's suggested name

  if (form) {
    const review = $('lo-review');
    if (review) {
      review.checked = localStorage.getItem(LS_REVIEW) === '1';
      review.addEventListener('change', () => localStorage.setItem(LS_REVIEW, review.checked ? '1' : '0'));
    }
    form.addEventListener('submit', (e) => {
      if (e.submitter && e.submitter.value === 'deny') return;
      const errors = syncHidden();
      if (errors.length) { e.preventDefault(); refresh(); errorEl.scrollIntoView({ block: 'center' }); }
    });
  }

  if (isDev) initDev();

  // ---------------------------------------------------------------- assertion generator
  function initDev() {
    const out = $('dev-result');
    const opt = (id) => devOptions.querySelector(`#${id}`);
    const request = async (method, url, body, json = true) => {
      const res = await fetch(url, {
        method,
        headers: body && json ? { 'content-type': 'application/json' } : body ? { 'content-type': 'application/xml' } : {},
        body: body == null ? undefined : json ? JSON.stringify(body) : body,
      });
      if (!res.ok) {
        const err = await res.json().catch(() => ({}));
        throw new Error(err.error_description || res.statusText);
      }
      return res.status === 204 ? null : res.json();
    };
    // Every change to server-side state reloads the page so lists and banners reflect it.
    const thenReload = (hash) => () => { location.hash = hash; location.reload(); };
    const fail = (what) => (err) => alert(`${what} failed: ${err.message}`);

    $('dev-rotate').addEventListener('click', (e) => {
      e.target.disabled = true;
      request('POST', data.rotateApi).then(thenReload('certificate'), (err) => { e.target.disabled = false; fail('Key rotation')(err); });
    });

    // Clock.
    $('dev-clock-amount').value = sessionStorage.getItem('localsaml.clockAmount') || $('dev-clock-amount').value;
    const amount = () => $('dev-clock-amount').value.trim().replace(/^[+-]/, '');
    const shiftClock = (body) => {
      sessionStorage.setItem('localsaml.clockAmount', $('dev-clock-amount').value);
      request('POST', data.clockApi, body).then(thenReload('clock'), fail('Changing the clock'));
    };
    $('dev-clock-advance').addEventListener('click', () => shiftClock({ advance: amount() }));
    $('dev-clock-back').addEventListener('click', () => shiftClock({ advance: `-${amount()}` }));
    $('dev-clock-reset').addEventListener('click', () => shiftClock({ reset: true }));

    // Faults.
    $('dev-fault-always').addEventListener('change', (e) => { $('dev-fault-count').disabled = e.target.checked; });
    $('dev-fault-add').addEventListener('click', () => {
      const body = { endpoint: $('dev-fault-endpoint').value };
      const status = $('dev-fault-status').value.trim();
      const tamper = $('dev-fault-tamper').value;
      const sp = $('dev-fault-sp').value.trim();
      const delay = Number($('dev-fault-delay').value) || 0;
      if (status) body.status = status;
      if (tamper) body.tamper = [tamper];
      if (sp) body.sp = sp;
      if (delay) body.delay_ms = delay;
      if ($('dev-fault-always').checked) body.always = true;
      else body.count = Math.max(1, Number($('dev-fault-count').value) || 1);
      request('POST', data.faultsApi, body).then(thenReload('faults'), fail('Arming the fault'));
    });
    $('dev-fault-clear').addEventListener('click', () => request('DELETE', data.faultsApi).then(thenReload('faults'), fail('Removing faults')));
    document.querySelectorAll('[data-fault]').forEach((btn) => btn.addEventListener('click', () =>
      request('DELETE', `${data.faultsApi}/${btn.dataset.fault}`).then(thenReload('faults'), fail('Removing the fault'))));

    // Sessions: "Forget" ends one without telling its service providers.
    document.querySelectorAll('[data-session]').forEach((btn) => btn.addEventListener('click', () => {
      btn.disabled = true;
      request('DELETE', `${data.sessionsApi}/${encodeURIComponent(btn.dataset.session)}`).then((json) => {
        const failed = json.deliveries.filter((d) => !d.ok);
        if (failed.length) alert(`Session ended, but ${failed.length} back-channel ${failed.length === 1 ? 'logout' : 'logouts'} failed:\n${failed.map((d) => `${d.sp}: ${d.outcome}`).join('\n')}`);
        thenReload('sessions')();
      }, fail('Ending the session'));
    }));

    // Service providers: register from a metadata URL or pasted metadata XML.
    $('dev-sp-add').addEventListener('click', () => {
      const text = $('dev-sp-metadata').value.trim();
      if (!text) return;
      const call = text.startsWith('<')
        ? request('POST', data.spsApi, text, false)
        : request('POST', data.spsApi, { metadata_url: text });
      call.then(thenReload('sps'), fail('Registering the service provider'));
    });
    document.querySelectorAll('[data-sp]').forEach((btn) => btn.addEventListener('click', () =>
      request('DELETE', `${data.spsApi}?entity_id=${encodeURIComponent(btn.dataset.sp)}`).then(thenReload('sps'), fail('Removing the service provider'))));

    const tri = (v) => (v === '' ? undefined : v === 'true');
    $('dev-generate').addEventListener('click', async () => {
      const { identity, errors } = build();
      if (errors.length) { refresh(); return; }
      syncHidden();
      const encrypt = opt('dev-encrypt').value;
      const body = {
        preset: state.preset,
        sp: opt('dev-sp').value.trim() || undefined,
        acs_url: opt('dev-acs').value.trim() || undefined,
        audience: opt('dev-audience').value.trim() || undefined,
        in_response_to: opt('dev-irt').value.trim() || undefined,
        relay_state: opt('dev-relay').value || undefined,
        expires_in: Number(opt('dev-ttl').value) || undefined,
        sign_response: tri(opt('dev-sign-response').value),
        sign_assertion: tri(opt('dev-sign-assertion').value),
        signature_algorithm: opt('dev-alg').value,
        encrypt: encrypt === '' ? undefined : encrypt !== 'none',
        encryption_algorithm: encrypt && encrypt !== 'none' ? encrypt : undefined,
        encrypt_name_id: tri(opt('dev-encrypt-name-id').value),
        encrypt_attributes: tri(opt('dev-encrypt-attributes').value),
        tamper: [...devOptions.querySelectorAll('.dev-tamper:checked')].map((c) => c.value),
        defaults: false,
        name_id: identity.name_id || undefined,
        name_id_format: identity.name_id_format,
        attributes: identity.attributes,
      };
      const btn = $('dev-generate');
      btn.disabled = true;
      try {
        const res = await fetch(data.api, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
        showResult(await res.json(), body, res.ok);
      } catch (err) {
        showResult({ error: String(err) }, body, false);
      } finally {
        btn.disabled = false;
      }
    });

    function postToAcs(json) {
      const f = h('form', { method: 'post', action: json.acs_url, target: '_blank' },
        h('input', { type: 'hidden', name: 'SAMLResponse', value: json.saml_response }),
        json.relay_state ? h('input', { type: 'hidden', name: 'RelayState', value: json.relay_state }) : null);
      document.body.append(f);
      f.submit();
      f.remove();
    }

    function showResult(json, req, ok) {
      out.hidden = false;
      out.replaceChildren();
      if (!ok) {
        out.append(h('div', { class: 'eyebrow error' }, 'Error'), h('pre', { class: 'code' }, json.error_description || JSON.stringify(json, null, 2)));
        out.scrollIntoView({ behavior: 'smooth', block: 'start' });
        return;
      }
      const chip = (text, cls = '') => h('span', { class: `chip ${cls}` }, text);
      const snippet = (title, text) => h('div', { class: 'snippet' }, h('div', { class: 'token-head' }, h('b', {}, title), copyBtn(text)), h('pre', { class: 'code wrap' }, text));
      const api = `curl -s -X POST ${data.api} -H 'content-type: application/json' -d '${JSON.stringify(req).replace(/'/g, "'\\''")}'`;
      out.append(
        h('div', { class: 'eyebrow' }, 'Result'),
        h('h2', {}, 'Response for ', h('span', { class: 'accent' }, json.sp)),
        h('div', { class: 'chips result-chips' },
          chip(json.signed.response ? 'response signed' : 'response unsigned', json.signed.response ? 'ok' : 'muted'),
          chip(json.signed.assertion ? 'assertion signed' : 'assertion unsigned', json.signed.assertion ? 'ok' : 'muted'),
          json.encrypted ? chip('encrypted', 'ok') : null,
          json.name_id_encrypted ? chip('NameID encrypted', 'ok') : null,
          json.attributes_encrypted ? chip('attributes encrypted', 'ok') : null,
          ...(req.tamper || []).map((t) => chip(t, 'bad'))),
        h('dl', { class: 'kv' },
          h('dt', {}, 'ACS URL'), h('dd', {}, h('code', {}, json.acs_url)),
          h('dt', {}, 'NameID'), h('dd', {}, h('code', {}, json.name_id), ' ', h('small', { class: 'muted' }, short(json.name_id_format)))),
        h('div', { class: 'actions' },
          h('button', { type: 'button', class: 'btn primary', onclick: () => postToAcs(json) }, 'POST to the ACS (new tab)'),
          copyBtn(json.saml_response, 'Copy SAMLResponse')),
        h('div', { class: 'snippet' }, h('div', { class: 'token-head' }, h('b', {}, 'SAML Response'), copyBtn(json.pretty)), xmlPre(json.pretty)),
        h('h2', {}, 'Use it'),
        snippet('Post it with curl', json.curl),
        snippet('Reproduce via the API', api),
        h('details', {}, h('summary', {}, 'Raw API response'), h('pre', { class: 'code wrap' }, JSON.stringify({ ...json, xml: '…', pretty: '…' }, null, 2))));
      out.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  }
})();

// ------------------------------------------------------------------ request inspector
// Polls the API and renders recent requests as a table whose rows expand to show their
// parameters, the SAML messages they carried and, for failures, the reason.
(function () {
  const root = document.getElementById('lo-requests');
  if (!root) return;
  const api = root.dataset.api;
  const $ = (id) => document.getElementById(id);

  let entries = []; // newest first
  let lastId = 0;
  let paused = false;
  const expanded = new Set();

  const failed = (e) => e.error || e.status >= 400;
  const time = (ms) => new Date(ms).toLocaleTimeString([], { hour12: false });

  function visible() {
    const sp = $('req-sp').value.trim();
    const errorsOnly = $('req-errors').checked;
    const all = $('req-all').checked;
    return entries.filter((e) => (all || e.category === 'flow')
      && (!sp || (e.sp || '').includes(sp))
      && (!errorsOnly || failed(e)));
  }

  function message(m) {
    const title = [h('span', { class: `dir ${m.direction}` }, m.direction), ' ', h('b', {}, m.kind),
      h('small', { class: 'muted' }, ` ${m.binding}${m.destination ? ` → ${m.destination.split('?')[0]}` : ''}${m.status ? ` · ${m.status}` : ''}`)];
    return h('div', { class: 'snippet req-message' }, h('div', { class: 'token-head' }, h('span', {}, title), copyBtn(m.xml)), xmlPre(m.xml));
  }

  function details(e) {
    const rows = [];
    const add = (label, value) => { if (value) rows.push(h('dt', {}, label), h('dd', {}, value)); };
    if (e.error) add('Why', h('span', {}, h('b', { class: 'req-error' }, e.error), e.error_description ? ` — ${e.error_description}` : ''));
    add('Request', h('code', {}, `${e.method} ${e.path}`));
    add('Outcome', e.error ? null : e.outcome);
    add('Service provider', e.sp && h('code', {}, e.sp));
    add('Redirected to', e.redirect && h('code', {}, e.redirect));
    const params = Object.entries(e.params);
    add('Parameters', params.length
      ? h('dl', { class: 'req-params' }, params.flatMap(([k, v]) => [h('dt', {}, k), h('dd', {}, v)]))
      : h('span', { class: 'muted' }, 'none'));
    add('SAML messages', e.messages.length ? h('div', { class: 'req-messages' }, e.messages.map(message)) : null);
    return h('dl', { class: 'req-details' }, rows);
  }

  function row(e) {
    const bad = failed(e);
    const toggle = (ev) => {
      if (ev.target.closest('button')) return;
      expanded.has(e.id) ? expanded.delete(e.id) : expanded.add(e.id); render();
    };
    // Sent messages are already in the outcome; list the received ones.
    const kinds = e.messages.filter((m) => m.direction === 'received').map((m) => `← ${m.kind}`).join(' ');
    const tr = h('tr', { class: `req-row${bad ? ' failed' : ''}${expanded.has(e.id) ? ' open' : ''}`, onclick: toggle },
      h('td', { class: 'mono' }, time(e.at)),
      h('td', {}, e.method),
      h('td', { class: 'mono' }, e.outgoing ? h('span', { class: 'req-issuer', title: 'Sent by localsaml' }, '→ out') : null,
        e.issuer !== 'root' ? h('span', { class: 'req-issuer' }, e.issuer) : null, e.endpoint),
      h('td', { class: 'mono' }, e.sp || '–'),
      h('td', {}, kinds ? h('small', { class: 'muted' }, kinds, ' · ') : null, bad && e.error ? h('span', { class: 'req-error' }, e.error) : e.outcome),
      h('td', {}, h('span', { class: `chip ${bad ? 'bad' : 'ok'}` }, String(e.status))),
      h('td', { class: 'num' }, e.duration_ms ? String(e.duration_ms) : '<1'));
    return expanded.has(e.id) ? [tr, h('tr', { class: 'req-detail' }, h('td', { colspan: 7 }, details(e)))] : [tr];
  }

  let rendered = false;
  function render() {
    rendered = true;
    const rows = visible();
    if (!rows.length) {
      root.replaceChildren(h('p', { class: 'muted req-empty' }, entries.length
        ? 'No requests match these filters.'
        : `No requests yet. Point your service provider at ${root.dataset.issuer} and they'll show up here.`));
      return;
    }
    const head = ['Time', 'Method', 'Endpoint', 'Service provider', 'Outcome', 'Status', 'ms'].map((t) => h('th', {}, t));
    root.replaceChildren(h('table', { class: 'req-table' }, h('thead', {}, h('tr', {}, head)), h('tbody', {}, rows.flatMap(row))));
  }

  async function poll() {
    if (!paused) {
      try {
        const res = await fetch(`${api}?after=${lastId}`, { cache: 'no-store' });
        const json = await res.json();
        // Only re-render on changes: replacing the rows loses clicks and text selections.
        let changed = !rendered;
        if (json.latest_id < lastId) { entries = []; lastId = 0; changed = true; } // the server restarted
        if (json.entries.length) {
          lastId = json.entries[0].id;
          entries = json.entries.concat(entries).slice(0, json.capacity);
          changed = true;
        }
        if (changed) render();
      } catch { /* server unreachable; try again */ }
    }
    setTimeout(poll, 1500);
  }

  for (const id of ['req-sp', 'req-errors', 'req-all']) $(id).addEventListener('input', render);
  $('req-pause').addEventListener('click', (ev) => {
    paused = !paused;
    ev.target.textContent = paused ? 'Resume' : 'Pause';
  });
  $('req-clear').addEventListener('click', async () => {
    await fetch(api, { method: 'DELETE' });
    entries = [];
    expanded.clear();
    render();
  });
  poll();
})();
